def glyph_for(code):
    return GLYPHS.get(chr(code), BLANK)


def encode_row(row):
    bits = 0
    for i in range(5):
        if i < len(row) and row[i] == '#':
            bits |= (16 >> i)
    return chr(40 + bits)


def main():
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(repo, 'kernel', 'tasks', 'console', 'font.tc')

    enc = []
    for code in range(0x20, 0x7F):
        g = glyph_for(code)
        for r in range(7):
            row = g[r] if r < len(g) else "....."
            enc.append(encode_row(row))
    s = ''.join(enc)
    assert len(s) == 95 * 7, len(s)

    # Split into 80-char chunks for readability; TC has no string
    # concatenation operator, so emit one literal (it fits well under
    # the lexer's token buffer).
    lines = ['// font.tc — GENERATED by tests/genfont.py — do not edit.',
             '// 5x7 bitmap font for /bin/console, ASCII 0x20-0x7E.',
             '// 7 chars per glyph; each char encodes one 5-bit pixel',
             '// row as (40 + bits), MSB = leftmost pixel.',
             '',
             '// console_font_w/h: glyph dimensions. cell adds 1px gap.',
             'export fn console_font_w() -> i32 { return 5; }',
             'export fn console_font_h() -> i32 { return 7; }',
             '',
             'export fn console_font() -> StringLiteral {']
    body = '    return "'
    for i in range(0, len(s), 80):
        body += s[i:i+80]
    body += '";'
    lines.append(body)
    lines.append('}')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (%d glyph-rows)' % (out, len(s)))


if __name__ == '__main__':
    main()
